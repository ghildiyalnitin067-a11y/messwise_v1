"""
Used Cooking Oil (UCO) Recycling — Database Model
===================================================
Tracks used cooking oil generated by the mess kitchen, its collection
status, recycling destination, and the estimated carbon benefit.

Workflow: Pending -> Collected -> Processed
Carbon savings are ONLY calculated for Processed quantities using a
documented, configurable emission factor.
"""
import uuid
from datetime import datetime, date, timezone
from sqlalchemy import Column, String, Float, Date, DateTime, Text, Boolean

from app.db.session import Base


class UcoRecord(Base):
    __tablename__ = "uco_records"

    id = Column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))

    # Admin Audit / Origin
    recorded_by = Column(String(255), nullable=False, default="Mess Supervisor")
    disposal_date = Column(Date, default=date.today, index=True, nullable=False)

    # Quantity & Normalisation
    quantity = Column(Float, nullable=False)                         # in declared unit (> 0)
    unit = Column(String(10), nullable=False, default="litres")       # "litres" | "kg"
    quantity_kg = Column(Float, nullable=True)                       # normalised to kg (density = 0.92 kg/L)

    # Partial Tracking Support
    collected_qty = Column(Float, nullable=True, default=0.0)        # amount collected so far
    processed_qty = Column(Float, nullable=True, default=0.0)        # amount processed so far

    # Oil Characteristics & Repurposing Partner
    oil_type = Column(String(100), nullable=True)                    # e.g. "Sunflower", "Mustard", "Palm", "Mixed"
    destination = Column(String(255), nullable=True)                 # recycling partner / destination
    repurposing_method = Column(String(100), nullable=True)          # e.g. "Biodiesel Production", "Industrial Soap & Bio-lubricants"

    # Status Workflow: Pending -> Collected -> Processed
    collection_status = Column(String(20), nullable=False, default="Pending", index=True)

    # Carbon Impact (Set automatically by carbon calculation service)
    co2_avoided_kg = Column(Float, nullable=True)                    # populated only for Processed quantities
    emission_factor_used = Column(Float, nullable=True)              # kg CO2e / kg UCO
    calculation_basis = Column(String(500), nullable=True)           # auditable formula, assumptions and source
    measurement_status = Column(String(50), nullable=True, default="Estimated") # "Estimated" | "Verified" | "Pending Factor Verification"

    # Administrative Tracking
    reference_number = Column(String(100), nullable=True)            # receipt / consignment / transfer note #
    remarks = Column(Text, nullable=True)                            # operational notes

    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), index=True)
    updated_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), onupdate=lambda: datetime.now(timezone.utc))
