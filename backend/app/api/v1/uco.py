"""
Used Cooking Oil (UCO) Recycling & Carbon Savings — API Router
==============================================================
Provides endpoints for recording kitchen oil disposal, tracking recycling
workflows (Pending -> Collected -> Processed), and generating auditable
carbon savings summaries.
"""
from typing import List, Optional
from datetime import date
from fastapi import APIRouter, Depends, Query, status, HTTPException
from sqlalchemy.ext.asyncio import AsyncSession

from app.db.session import get_db
from app.api.deps import require_role
from app.models.user import User
from app.services.uco_service import uco_service, SAFETY_GUIDELINES, METHODOLOGY_SUMMARY
from app.schemas.uco import (
    UcoCreateRequest,
    UcoUpdateRequest,
    UcoTransitionRequest,
    UcoRecordOut,
    UcoSummaryResponse
)
from app.core.carbon_factors import REPURPOSING_PATHWAYS, UCO_DENSITY_KG_PER_LITRE

router = APIRouter(prefix="/uco", tags=["Used Cooking Oil Recycling & Carbon Savings"])


@router.get("", response_model=List[UcoRecordOut])
@router.get("/", response_model=List[UcoRecordOut])
async def list_uco_records(
    status: Optional[str] = Query(default=None, description="Filter by status (Pending, Collected, Processed)"),
    oil_type: Optional[str] = Query(default=None, description="Filter by oil type"),
    start_date: Optional[date] = Query(default=None, description="Filter start date (YYYY-MM-DD)"),
    end_date: Optional[date] = Query(default=None, description="Filter end date (YYYY-MM-DD)"),
    limit: int = Query(default=100, ge=1, le=500),
    offset: int = Query(default=0, ge=0),
    db: AsyncSession = Depends(get_db)
):
    """Lists used cooking oil disposal records with optional filtering."""
    return await uco_service.get_records(
        db=db,
        status_filter=status,
        oil_type=oil_type,
        start_date=start_date,
        end_date=end_date,
        limit=limit,
        offset=offset
    )


@router.get("/summary", response_model=UcoSummaryResponse)
async def get_uco_summary(
    start_date: Optional[date] = Query(default=None, description="Start date for summary filtering"),
    end_date: Optional[date] = Query(default=None, description="End date for summary filtering"),
    db: AsyncSession = Depends(get_db)
):
    """
    Returns aggregated KPIs, carbon avoided metrics, monthly trends,
    status distribution, and transparent methodology metadata.
    """
    return await uco_service.get_summary(db=db, start_date=start_date, end_date=end_date)


@router.get("/methodology")
async def get_uco_methodology():
    """Returns transparent scientific configuration and emission factors."""
    return {
        "density_standard_kg_per_litre": UCO_DENSITY_KG_PER_LITRE,
        "standard_reference": "ASTM D4052 / FSSAI RUCO standard (0.92 kg/L at 20-25 deg C)",
        "formula": "Estimated emissions avoided (kg CO2e) = Eligible quantity processed (kg) x Pathway net factor",
        "rules": [
            "Pending and Collected quantities yield zero carbon savings until processing is confirmed.",
            "Net factors account for fossil diesel displacement minus refining and transport emissions.",
            "Unrecognized pathways display 'Carbon savings pending verified emission factor'."
        ],
        "pathways": REPURPOSING_PATHWAYS,
        "safety_guidelines": SAFETY_GUIDELINES,
        "methodology_summary": METHODOLOGY_SUMMARY
    }


@router.post("", response_model=UcoRecordOut, status_code=status.HTTP_201_CREATED)
@router.post("/", response_model=UcoRecordOut, status_code=status.HTTP_201_CREATED)
async def create_uco_record(
    req: UcoCreateRequest,
    current_user: User = Depends(require_role(["admin"])),
    db: AsyncSession = Depends(get_db)
):
    """
    Manually records used cooking oil generated by the mess kitchen.
    Restricted to authorized mess admins.
    """
    supervisor = (
        current_user.admin_profile.name 
        if current_user.admin_profile and current_user.admin_profile.name 
        else current_user.username or "Mess Supervisor"
    )
    return await uco_service.create_record(db=db, req=req, recorded_by=supervisor)


@router.get("/{record_id}", response_model=UcoRecordOut)
async def get_uco_record(
    record_id: str,
    db: AsyncSession = Depends(get_db)
):
    """Fetches a specific UCO record by ID."""
    return await uco_service.get_record_by_id(db=db, record_id=record_id)


@router.put("/{record_id}", response_model=UcoRecordOut)
async def update_uco_record(
    record_id: str,
    req: UcoUpdateRequest,
    current_user: User = Depends(require_role(["admin"])),
    db: AsyncSession = Depends(get_db)
):
    """
    Updates an existing UCO record. Restricted to authorized admins.
    Recalculates carbon savings when quantity, method, or status changes.
    """
    return await uco_service.update_record(db=db, record_id=record_id, req=req)


@router.post("/{record_id}/transition", response_model=UcoRecordOut)
async def transition_uco_status(
    record_id: str,
    req: UcoTransitionRequest,
    current_user: User = Depends(require_role(["admin"])),
    db: AsyncSession = Depends(get_db)
):
    """
    Transitions the recycling workflow (Pending -> Collected -> Processed).
    Supports partial processing to prevent double-counting.
    """
    supervisor = (
        current_user.admin_profile.name 
        if current_user.admin_profile and current_user.admin_profile.name 
        else "Mess Supervisor"
    )
    return await uco_service.transition_record(
        db=db,
        record_id=record_id,
        req=req,
        admin_name=supervisor
    )


@router.delete("/{record_id}")
async def delete_uco_record(
    record_id: str,
    current_user: User = Depends(require_role(["admin"])),
    db: AsyncSession = Depends(get_db)
):
    """Deletes a UCO entry. Restricted to authorized admins."""
    return await uco_service.delete_record(db=db, record_id=record_id)
